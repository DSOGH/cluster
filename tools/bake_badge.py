"""Bake the M340i layout's badge ("M340" at the top, in Pirulen, the design's numerals' face) as an r8 picture:
python3 tools/bake_badge.py Pirulen.ttf  ->  apps/cluster_layouts/m340_badge.js (the font file is not kept here)."""
import base64, os, sys, zlib
from PIL import Image, ImageDraw, ImageFont

TEXT, SIZE, TRACK, PAD = 'M340', 34, 6, 4
font = ImageFont.truetype(sys.argv[1], SIZE)
W = sum(font.getbbox(c)[2] for c in TEXT) + TRACK * (len(TEXT) - 1) + 2 * PAD + 40
img = Image.new('L', (W, SIZE * 2), 0)
d = ImageDraw.Draw(img)
x = PAD
for c in TEXT:
    d.text((x, PAD), c, font=font, fill=255)
    x += font.getlength(c) + TRACK
box = img.getbbox()
img = img.crop((max(0, box[0] - PAD), max(0, box[1] - PAD), box[2] + PAD, box[3] + PAD))
w, h = img.size
blob = base64.b64encode(zlib.compress(img.tobytes(), 9)).decode()
out = os.path.join(os.path.dirname(__file__), '..', 'apps', 'cluster_layouts', 'm340_badge.js')
open(out, 'w', newline='\n').write(f"""'use strict';
/* GENERATED by tools/bake_badge.py: the M340i layout's badge ("{TEXT}", Pirulen) as an r8 picture. Do not edit. */
const zlib = require('zlib');
const BADGE = {{ w: {w}, h: {h} }};
const BLOB = '{blob}';
let px = null;
/** The badge as a texture for a piece's `textures`. */
function tex() {{
    const f = () => ({{ w: BADGE.w, h: BADGE.h, px: px || (px = zlib.inflateSync(Buffer.from(BLOB, 'base64'))), format: 'r8', sampling: 'bilinear' }});
    f.id = 'm340.badge';
    return f;
}}
module.exports = {{ BADGE, tex }};
""")
img.save(os.path.join(os.environ.get('PREVIEW_DIR', '.'), 'badge.png'))
print(w, h, len(blob))
